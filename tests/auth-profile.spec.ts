import { test, expect } from '@playwright/test';

test('local signup, profile completion, logout and login', async ({ page }, info) => {
  await page.goto('/signup');
  await expect(page.getByRole('heading', { name: 'Sign up for Earnist' })).toBeVisible();
  await page.getByLabel('Email address').fill('alex@example.com');
  await page.getByLabel('Password', { exact: true }).fill('sample-pass-123');
  await page.getByRole('button', { name: 'Create local account' }).click();
  await expect(page.getByRole('button', { name: 'Try with sample data' })).toBeVisible();
  await page.getByRole('button', { name: 'Try with sample data' }).click();
  await page.getByRole('button', { name: 'Skip for now' }).click();
  await expect(page.locator('.onboarding-panel h1')).toHaveText(/A little less admin\.|Your persona is ready\./);
  const trial = page.getByRole('button', { name: 'Finish free trial' });
  if (await trial.isVisible()) await trial.click();
  await page.getByRole('button', { name: 'Start with empty local records' }).click();
  await page.goto('/profile');
  await expect(page.getByRole('progressbar', { name: 'Profile completion' })).toHaveAttribute('value', '11');
  await page.getByLabel('Display name').fill('Alex Morgan');
  await page.getByLabel('Phone number').fill('555 123 4567');
  await page.getByLabel('Business name').fill('Morgan Studio');
  await page.getByLabel('Business activity').fill('Design consulting');
  await page.getByLabel('How do you earn?').selectOption('Freelancer');
  await page.getByLabel('Business location').fill('Brooklyn, NY');
  await page.getByLabel('Website or portfolio').fill('https://example.com');
  await expect(page.getByRole('progressbar', { name: 'Profile completion' })).toHaveAttribute('value', '89');
  await page.getByLabel('Upload profile photo').setInputFiles({ name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from('not an image') });
  await expect(page.getByRole('alert')).toContainText('This image could not be opened');
  await expect(page.getByRole('progressbar', { name: 'Profile completion' })).toHaveAttribute('value', '89');
  const imageData = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 32; canvas.height = 32; const context = canvas.getContext('2d')!; context.fillStyle = '#7faa31'; context.fillRect(0, 0, 32, 32); return canvas.toDataURL('image/png'); });
  await page.getByLabel('Upload profile photo').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from(imageData.split(',')[1], 'base64') });
  await expect(page.getByAltText('Your profile photo')).toBeVisible();
  await expect(page.getByRole('progressbar', { name: 'Profile completion' })).toHaveAttribute('value', '100');
  await page.getByRole('button', { name: 'Save profile' }).click();
  await page.reload();
  await expect(page.getByAltText('Your profile photo')).toBeVisible();
  await expect(page.locator('.profile-avatar img')).toBeVisible();
  await expect(page.getByRole('link', { name: 'Open local profile, 100% complete' })).toBeVisible();
  await expect(page.locator('.profile-progress-fill')).toHaveAttribute('stroke-dasharray', '100 100');
  await expect(page.getByRole('progressbar', { name: 'Profile completion' })).toHaveAttribute('value', '100');
  await page.locator('.app-header').screenshot({ path: `test-results/profile-header-${info.project.name}.png` });
  await page.locator('.completion-panel').screenshot({ path: `test-results/profile-completion-${info.project.name}.png` });
  await page.getByRole('button', { name: 'Log out' }).click();
  await expect(page.getByRole('heading', { name: 'Log in to Earnist' })).toBeVisible();
  await page.getByLabel('Email address').fill('alex@example.com');
  await page.getByLabel('Password', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Email or password is incorrect');
  await page.getByLabel('Password', { exact: true }).fill('sample-pass-123');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Log in to Earnist' })).toHaveCount(0);
  await page.goto('/profile');
  await expect(page.getByRole('progressbar', { name: 'Profile completion' })).toHaveAttribute('value', '100');
  await page.getByRole('button', { name: 'Remove photo' }).click();
  await expect(page.getByAltText('Your profile photo')).toHaveCount(0);
  await expect(page.getByRole('progressbar', { name: 'Profile completion' })).toHaveAttribute('value', '89');
  await expect(page.getByRole('link', { name: 'Open local profile, 89% complete' })).toBeVisible();
});
